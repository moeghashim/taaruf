 let completed = false, withdrawn = false, failure = false;
 await page.route("**/*", async route => {
  const url=new URL(route.request().url()); if(url.hostname!=="127.0.0.1") return route.abort();
  if(!url.pathname.startsWith("/api/")) return route.continue();
  if(url.pathname!=="/api/admin/bridge") return route.fulfill({json:{}});
  const {name,kind}=route.request().postDataJSON(); expect(kind).toBe("query");
  if(failure && name==="interests.getAll") return route.fulfill({status:401,json:{error:"expired"}});
  const submissions=people.map((p,n)=>({id:"i"+n,fromRegistrationId:p._id,toRegistrationId:people[1-n]._id,source:n?"whatsapp":"email",createdAt:1}));
  const rows=submissions.map((s,n)=>({_id:s.id,...s,eventId:"e",event,fromRegistration:people[n],toRegistration:people[1-n],status:withdrawn&&n===1?"withdrawn":"new",visibility:"admin_actionable",createdAt:1,updatedAt:1,match:null,mutual:withdrawn?null:{state:completed?"completed":"open",submissions}}));
  let result: unknown=[];
  if(name==="registrations.getAll") result=people;
  if(name==="interests.getAll") result=rows;
  if(name==="matches.workbenchPage") result={page:[],isDone:true,continueCursor:""};
  if(name==="events.profileFilterCatalog") result={page:[event,{...event,_id:"other",title:"Other event"}],isDone:true,continueCursor:""};
  return route.fulfill({json:{result}});
 });
 await page.goto("/admin/workbench?interest=i0");
 await expect(page.getByText("Mutual interest · Open").first()).toBeVisible();
