 await expect(page.getByText("Mutual interest · Open").first()).toBeVisible();
 await page.getByRole("checkbox",{name:"Mutual only",exact:true}).check();
 await expect(page.getByText("2 shown",{exact:true})).toBeVisible();
 await page.getByPlaceholder("Interest notes...").first().fill("Unsaved synthetic note");
 await page.evaluate(()=>window.dispatchEvent(new Event("focus")));
 await expect(page.getByPlaceholder("Interest notes...").first()).toHaveValue("Unsaved synthetic note");
 await page.screenshot({path:info.outputPath("interests-"+width+".png"),fullPage:true});
 await page.goto("/admin/workbench?interest=i0");
 await page.getByRole("checkbox",{name:/Mutual only/}).check();
 await page.locator("select").filter({ has: page.locator("option", { hasText: "Select an interest" }) }).selectOption("i0");
 completed=true; await page.evaluate(()=>window.dispatchEvent(new Event("admin-data-refresh")));
 await expect(page.getByText("Mutual interest · Completed").first()).toBeVisible();
 expect(await page.locator("body").evaluate(el=>el.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath("mutual-"+width+".png"),fullPage:true});
 withdrawn=true; await page.evaluate(()=>window.dispatchEvent(new Event("admin-data-refresh")));
 await expect(page.getByText("0 interests · 0 matches.",{exact:false})).toBeVisible();
 failure=true; await page.evaluate(()=>window.dispatchEvent(new Event("admin-data-refresh")));
